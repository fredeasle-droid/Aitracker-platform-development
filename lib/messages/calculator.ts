export type CalculatorText = (typeof calculatorBase)['da']

const calculator: Record<Locale, CalculatorText> = {
  ...calculatorBase,
  ...newLocales(calculatorBase, (pack, fallback, locale) => ({ ...fallback, ...pack.calculator, ...LOCALE_MONEY[locale] })),
}

export function calculatorText(locale: Locale): CalculatorText {
  return calculator[locale]
}

export function fill(template: string, vars: Record<string, string>) {
  return template.replace(/\{(\w+)\}/g, (match, name: string) => vars[name] ?? match)
}

export function calculatorFormat(text: CalculatorText) {
  const money = new Intl.NumberFormat(text.numberTag, { style: 'currency', currency: text.currency, minimumFractionDigits: 2, maximumFractionDigits: 2 })
  const whole = new Intl.NumberFormat(text.numberTag, { maximumFractionDigits: 0 })
  const decimal = new Intl.NumberFormat(text.numberTag, { minimumFractionDigits: 2, maximumFractionDigits: 2 })
  return {
    money: (n: number) => money.format(n),
    whole: (n: number) => whole.format(n),
    pct: (n: number) => `${decimal.format(n)} %`,
  }
}
