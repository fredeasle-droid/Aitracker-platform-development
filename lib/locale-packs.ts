import tr from './locale-packs/tr.json'
import cs from './locale-packs/cs.json'
import el from './locale-packs/el.json'
import hu from './locale-packs/hu.json'
import hr from './locale-packs/hr.json'
import sk from './locale-packs/sk.json'
import mx from './locale-packs/mx.json'
import ar from './locale-packs/ar.json'
import ch from './locale-packs/ch.json'
import at from './locale-packs/at.json'
import be from './locale-packs/be.json'
import { BASE_LOCALES, LOCALE_SOURCE, NEW_LOCALES, type BaseTranslated, type Locale, type NewLocale } from './locale-list'

type Dict = Record<string, string>

// Generated by scripts/i18n/translate-locales.mjs. `ready` is only set once every section is translated.
export type LocalePack = {
  ready?: boolean
  ui?: Dict
  data?: Dict
  daily?: Record<string, unknown>
  faqPage?: Record<string, unknown>
  seo?: Record<string, unknown>
  calculator?: Dict
  account?: string
  sections?: Dict
  slugs?: Dict
  pages?: Dict
}

export const LOCALE_PACKS = { tr, cs, el, hu, hr, sk, mx, ar, ch, at, be } as unknown as Record<NewLocale, LocalePack>

// A market goes live (language menu, routing, sitemap, hreflang) only when its whole pack exists,
// so Google never sees half-translated or fallback pages under a new prefix.
export const LAUNCHED_LOCALES: Locale[] = [...BASE_LOCALES, ...NEW_LOCALES.filter((locale) => LOCALE_PACKS[locale].ready === true)]

export function isLaunched(locale: Locale) {
  return LAUNCHED_LOCALES.includes(locale)
}

export function newLocales<T>(base: Record<BaseTranslated, T>, pick: (pack: LocalePack, fallback: T, locale: NewLocale) => T): Record<NewLocale, T> {
  return Object.fromEntries(NEW_LOCALES.map((locale) => [locale, pick(LOCALE_PACKS[locale], base[LOCALE_SOURCE[locale]], locale)])) as Record<NewLocale, T>
}

export function fillTemplate(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}
