type Dictionary = Record<string, string>

const base: Record<string, Dictionary> & Record<'en' | 'sv' | 'no' | 'de' | 'es' | 'br' | 'pt' | 'fr' | 'it' | 'pl' | 'fi' | 'nl', Dictionary> = { en, sv, no, de, es, br, pt, fr, it, pl, fi, nl }
const added = { tr, cs, el, hu, hr, sk, mx, ar, ch, at, be } as Record<NewLocale, Dictionary>

// Home page and site chrome copy, keyed by the Danish source text. Generated by scripts/i18n/translate-home.mjs
// and scripts/i18n/translate-locales.mjs.
export const homePageMessages: Record<Exclude<Locale, 'da'>, Dictionary> = {
  ...base,
  ...newLocales(base, (_pack, fallback, locale) => ({ ...fallback, ...added[locale] })),
}
